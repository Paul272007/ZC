Create::Create(
  const bool force, const bool edit, const std::vector<std::string> &files,
  const std::vector<std::string> &input_files
)
  : Command(force), edit_(edit)
{
  for (CAA f : files)
  {
    if (!force_ && fs::exists(f) &&
        !if_.ask("The file '" + f + "' already exists. Do you want to replace it ?"))
    {
      if_.info("Skipped file " + f);
      continue;
    }
    if (Language l = language_of(f);files_.contains(l))
      files_.at(l).emplace_back(f);
    else
      files_[l] = { f };
  }
  for (CAA f : input_files)
  {
    if (!fs::exists(f))
      throw ZCException(ZCE_NOT_FOUND, "Input file " + f + " not found.");
    if (Language l = language_of(f);input_files_.contains(l))
      input_files_.at(l).emplace_back(f);
    else
      input_files_[l] = { f };
  }
}

void Create::operator()()
{
  for (CAA[lang, files] : files_)
  {
    switch (lang)
    {
    case H:
      if (input_files_.contains(C))
      {
        get_declarations(C);
        for (CAA f : files)
        {
          try
          {
            write_declarations(f, C);
            files_to_edit_.push_back(f);
          }
          catch (const ZCException &)
          {
            continue;
          }
        }
      }
      break;
    case HXX:
      if (input_files_.contains(CXX))
      {
        get_declarations(CXX);
        for (CAA f : files)
        {
          try
          {
            write_declarations(f, CXX);
            files_to_edit_.push_back(f);
          }
          catch (const ZCException &)
          {
            continue;
          }
        }
      }
      break;
    default:
      for (CAA f : files)
        if (te_.init_with_template(f, lang, force_))
          files_to_edit_.push_back(f);
      break;
    }
  }

  if ((gc_.open_after_create || edit_) && !files_to_edit_.empty())
  {
    stringstream cmd;
    cmd << gc_.editor;
    for (const auto &f : files_to_edit_)
      cmd << " " << escape_shell_arg(f);
    if (system(cmd.str().c_str()) != 0)
      throw ZCException(ZCE_INTERNAL_ERROR, "Could not open file(s) in editor");
  }
}

void Create::get_declarations(const Language l)
{
  for (CAA file : input_files_.at(l))
  {
    Declarations d = parse_declarations(file);
    merge_declarations(d, l);
  }
}

void Create::merge_declarations(const Declarations &src, Language dest)
{
  Declarations &d = declarations_[dest];
  merge(src.includes, d.includes);
  merge(src.macros, d.macros);
  merge(src.typedefs, d.typedefs);
  merge(src.enums, d.enums);
  merge(src.structs, d.structs);
  merge(src.unions, d.unions);
  merge(src.globals, d.globals);
  merge(src.functions, d.functions);
}

void Create::write_declarations(const std::filesystem::path &f, const Language l) const
{
  stringstream content;
  auto [includes, macros, typedefs, enums, structs, unions, globals, functions] = declarations_.at(l);

  // Custom header
  const string s = std::format("{:%F %T}", chrono::floor<chrono::seconds>(chrono::system_clock::now()));
  content << "// --- This file was automatically generated by ZC\n";
  content << "// --- Date of creation: " << s << " (UTC)\n\n";

  // Header guard
  content << "#pragma once\n\n";

  if (!includes.empty())
  {
    content << "/* Includes */\n";
    for (const auto &inc : includes)
      content << inc;
    content << '\n';
  }

  if (!macros.empty())
  {
    content << "/* Macros */\n";
    for (const auto &macro : macros)
      content << "#define " << macro << '\n';
    content << '\n';
  }

  if (l == C)
    content << "#ifdef __cplusplus\n"
            << "extern \"C\"\n"
            << "{\n"
            << "#endif\n\n";

  if (!enums.empty())
  {
    content << "/* Enums */\n";
    for (const auto &en : enums)
      content << en << ";\n\n";
  }

  if (!unions.empty())
  {
    content << "/* Unions */\n";
    for (const auto &un : unions)
      content << un << ";\n\n";
  }

  if (!structs.empty())
  {
    content << "/* Structures */\n";
    for (const auto &struc : structs)
      content << struc << ";\n\n";
  }

  if (!typedefs.empty())
  {
    content << "/* Typedefs */\n";
    for (const auto &td : typedefs)
      content << td << ";\n\n";
  }

  if (!globals.empty())
  {
    content << "/* Global variables */\n";
    for (const auto &glob : globals)
      content << glob << ";\n";
    content << '\n';
  }

  if (!functions.empty())
  {
    content << "/* Functions */\n";
    for (const auto &func : functions)
      content << func << ";\n";
    content << '\n';
  }

  if (l == C)
    content << "#ifdef __cplusplus\n"
            << "}\n"
            << "#endif\n";

  write_file(f, content.str());
}

